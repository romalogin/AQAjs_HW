// For 1 number

console.log("-------------------------For---------------------------");

let number = 2;

for (let i = 1; i < 11; i++) {
    console.log(`${number} x ${i} = ${number*i}`);
}

console.log("-------------------------While---------------------------");

let count = 1;
while (count <= 10){
    console.log((`${number} x ${count} = ${number*count}`))
    count++;
}

